# export_models.py: writes the fitted models the game uses from sounds.json (fit_models.py's output) into
# src/1b-sound-models.js as one exported constant, SOUND_MODELS. Only the names given are exported, so the game ships
# only the models it plays. Rerun after refitting; never edit 1b-sound-models.js by hand.
# Usage: python3 -I export_models.py <sounds.json> <out .js> <model name> [<model name> ...]
import json, sys

def main(json_path, out_path, names):
    models = json.load(open(json_path))['models']
    missing = [n for n in names if n not in models]
    if missing:
        sys.exit(f'not in {json_path}: {", ".join(missing)}')
    lines = [
        '// 1b-sound-models.js: FITTED SOUND MODELS, generated by tools/sound/export_models.py from fit_models.py output.',
        '// Do not edit by hand: refit and re-export. Played by 8c-audio.js; tunables are SOUND in 1-config.js.',
        '// bandModel: shared noise -> bandpass per bandHz (bandQ) -> gain following gains[band] through breakpointsMs.',
        'export const SOUND_MODELS = {',
    ]
    for i, n in enumerate(names):
        m = models[n]
        sep = ',' if i < len(names) - 1 else ''
        lines.append(f'  {n}: {json.dumps(m, separators=(",", ":"))}{sep}')
    lines.append('};')
    open(out_path, 'w').write('\n'.join(lines) + '\n')
    print(f'wrote {out_path}: {", ".join(names)}')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
